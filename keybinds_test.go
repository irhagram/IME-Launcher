const sampleCfg = "// generated by CitizenFX\r\nunbindall\r\nbind KEYBOARD I \"e tablet\"\r\nseta \"cl_nickname\" \"irham\"\r\nrbind core KEYBOARD TAB \"+scoreboard\"\r\nrbind ui KEYBOARD ESCAPE \"+esc\"\r\n"

func TestParseKeybinds(t *testing.T) {
	got := parseKeybinds(sampleCfg)
	if len(got) != 1 || got[0] != (Keybind{"KEYBOARD", "I", "e tablet", false}) {
		t.Fatalf("got %+v", got)
	}
	// rbind must never be read as a user bind
	if len(parseKeybinds("rbind core KEYBOARD TAB \"+scoreboard\"\n")) != 0 {
		t.Error("rbind parsed as bind")
	}
	// unquoted command and lowercase are accepted
	if g := parseKeybinds("bind keyboard f5 say_hi\n"); len(g) != 1 || g[0] != (Keybind{"KEYBOARD", "F5", "say_hi", false}) {
		t.Errorf("unquoted: %+v", g)
	}
}

func TestValidKeybind(t *testing.T) {
	if b, err := validKeybind(Keybind{"", " f5 ", " e tablet ", false}); err != nil || b != (Keybind{"KEYBOARD", "F5", "e tablet", false}) {
		t.Errorf("got %+v %v", b, err)
	}
	for _, bad := range []Keybind{
		{"KEYBOARD", "", "x", false},
		{"KEYBOARD", "F 5", "x", false},
		{"KEYBOARD", "I", "", false},
		{"KEYBOARD", "I", `a"b`, false},
		{"KEYBOARD", "I", `a;b`, false},
		{"KEYBOARD", "I", `a\b`, false},
		{"KEYBOARD", "I", "a\nb", false},
		{"KEY BOARD", "I", "x", false},
		{"KEYBOARD", "I", strings.Repeat("a", maxBindCmdLen+1), false},
	} {
		if _, err := validKeybind(bad); err == nil {
			t.Errorf("%+v should fail", bad)
		}
	}
}

func TestValidKeybindsDuplicate(t *testing.T) {
	_, err := validKeybinds([]Keybind{{"KEYBOARD", "I", "a", false}, {"keyboard", "i", "b", false}})
	if err == nil {
		t.Error("duplicate key must be refused")
	}
	if _, err := validKeybinds([]Keybind{{"KEYBOARD", "I", "a", false}, {"MOUSE_BUTTON", "I", "b", false}}); err != nil {
		t.Errorf("same key on another mapper is fine: %v", err)
	}
}

func TestApplyKeybinds(t *testing.T) {
	got := applyKeybinds(sampleCfg, []Keybind{{"KEYBOARD", "I", "e tablet", false}, {"KEYBOARD", "F5", "say hi", false}})
	want := "// generated by CitizenFX\r\nunbindall\r\n" +
		"bind KEYBOARD I \"e tablet\"\r\nbind KEYBOARD F5 \"say hi\"\r\n" +
		"seta \"cl_nickname\" \"irham\"\r\nrbind core KEYBOARD TAB \"+scoreboard\"\r\nrbind ui KEYBOARD ESCAPE \"+esc\"\r\n"
	if got != want {
		t.Errorf("got:\n%q\nwant:\n%q", got, want)
	}
	// removing every bind keeps everything else
	got = applyKeybinds(sampleCfg, nil)
	if strings.Contains(got, "bind KEYBOARD") && !strings.Contains(got, "rbind") || strings.Contains(got, "\nbind ") {
		t.Errorf("binds not removed: %q", got)
	}
	if !strings.Contains(got, "rbind core KEYBOARD TAB") || !strings.Contains(got, "cl_nickname") || !strings.Contains(got, "unbindall") {
		t.Errorf("other lines lost: %q", got)
	}
	// idempotent
	if applyKeybinds(sampleCfg, parseKeybinds(sampleCfg)) != sampleCfg {
		t.Error("saving the same list must not change the file")
	}
}

func TestApplyKeybindsPlacement(t *testing.T) {
	// no old bind: goes right after unbindall
	got := applyKeybinds("unbindall\nseta \"a\" \"1\"\n", []Keybind{{"KEYBOARD", "J", "x", false}})
	if got != "unbindall\nbind KEYBOARD J \"x\"\nseta \"a\" \"1\"\n" {
		t.Errorf("after unbindall: %q", got)
	}
	// no unbindall: appended; LF line endings preserved
	got = applyKeybinds("seta \"a\" \"1\"\n", []Keybind{{"KEYBOARD", "J", "x", false}})
	if got != "seta \"a\" \"1\"\nbind KEYBOARD J \"x\"\n" {
		t.Errorf("append: %q", got)
	}
	if applyKeybinds("", nil) != "" {
		t.Error("empty stays empty")
	}
}

func TestValidKeybindsDisabledMaySharedKey(t *testing.T) {
	in := []Keybind{{"KEYBOARD", "I", "a", false}, {"KEYBOARD", "I", "b", true}, {"KEYBOARD", "I", "c", true}}
	if _, err := validKeybinds(in); err != nil {
		t.Errorf("disabled binds may share a key with an enabled one: %v", err)
	}
	in[1].Disabled = false
	if _, err := validKeybinds(in); err == nil {
		t.Error("two enabled binds on one key must be refused")
	}
	if _, err := validKeybinds([]Keybind{{"KEYBOARD", "I", `a"b`, true}}); err == nil {
		t.Error("a disabled bind is validated too")
	}
}

func TestSaveKeybindsDisableEnable(t *testing.T) {
	appdata := t.TempDir()
	t.Setenv("APPDATA", appdata)
	cfgPath, _ := fivemCfgPath()
	os.MkdirAll(filepath.Dir(cfgPath), 0o755)
	os.WriteFile(cfgPath, []byte(sampleCfg), 0o644)
	old := fivemRunning
	fivemRunning = func() bool { return false }
	defer func() { fivemRunning = old }()

	a := &App{cfg: newConfigStore(filepath.Join(appdata, "config.json"))}
	a.status = LauncherStatus{State: "ok"}

	// disable the existing bind: gone from fivem.cfg, kept in the config
	if r := a.SaveKeybinds([]Keybind{{"KEYBOARD", "I", "e tablet", true}}); !r.OK {
		t.Fatal(r.Msg)
	}
	b, _ := os.ReadFile(cfgPath)
	if regexp.MustCompile(`(?m)^bind `).Match(b) || !strings.Contains(string(b), "rbind core") {
		t.Errorf("bind must be removed, rest kept: %q", b)
	}
	list := a.GetKeybinds()
	if len(list.Items) != 1 || !list.Items[0].Disabled || list.Items[0].Command != "e tablet" {
		t.Fatalf("disabled bind must still be listed: %+v", list.Items)
	}
	// survives a restart of the launcher (config.json)
	a2 := &App{cfg: newConfigStore(filepath.Join(appdata, "config.json"))}
	if l := a2.GetKeybinds(); len(l.Items) != 1 || !l.Items[0].Disabled {
		t.Fatalf("not persisted: %+v", l.Items)
	}

	// enable it again: back in fivem.cfg, gone from the disabled list
	if r := a.SaveKeybinds([]Keybind{{"KEYBOARD", "I", "e tablet", false}}); !r.OK {
		t.Fatal(r.Msg)
	}
	b, _ = os.ReadFile(cfgPath)
	if !strings.Contains(string(b), `bind KEYBOARD I "e tablet"`) {
		t.Errorf("bind must be back: %q", b)
	}
	if got := a.cfg.get().DisabledBinds; len(got) != 0 {
		t.Errorf("disabled list must be empty: %+v", got)
	}

	// refused while FiveM runs, nothing changes
	fivemRunning = func() bool { return true }
	if r := a.SaveKeybinds(nil); r.OK {
		t.Error("must refuse while FiveM is open")
	}
}
