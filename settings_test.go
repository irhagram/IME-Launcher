func TestValidNickname(t *testing.T) {
	ok := map[string]string{
		"  Budi Santoso ":       "Budi Santoso",
		"NAMA NYA DISINI":       "NAMA NYA DISINI",
		"Ünï_çødé ✓":            "Ünï_çødé ✓",
		strings.Repeat("a", 30): strings.Repeat("a", 30),
	}
	for in, want := range ok {
		if got, err := validNickname(in); err != nil || got != want {
			t.Errorf("validNickname(%q) = %q, %v; want %q", in, got, err, want)
		}
	}
	for _, bad := range []string{"", "   ", strings.Repeat("a", 31), `a"b`, `a\b`, "a;b", "line\nbreak", "tab\there"} {
		if _, err := validNickname(bad); err == nil {
			t.Errorf("validNickname(%q) should fail", bad)
		}
	}
}

